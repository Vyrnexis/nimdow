## wlgen: generates Nim bindings from Wayland protocol XML files.
##
## For every `protocol/*.xml` it writes `src/nimdowpkg/wl/protocols/<name>.nim`
## (opaque proxy types, request procs over `wl_proxy_marshal_flags`, listener
## types + `add_listener`, enum constants) and, for every protocol except the
## core `wayland` one, runs `wayland-scanner private-code` to produce the
## `<name>_protocol.c` interface tables which the module compiles via
## `{.compile.}`.
##
## Run from anywhere: `nim r tools/wlgen.nim [protocolDir [outDir]]`
import std/[xmlparser, xmltree, os, strutils, tables, sets, algorithm, osproc]

type
  Arg = object
    name, kind, iface: string
  Msg = object
    name, summary: string
    since: int
    destructor: bool
    args: seq[Arg]
  Entry = object
    name, value: string
  Enum = object
    name: string
    entries: seq[Entry]
  Iface = object
    name: string
    version: int
    requests, events: seq[Msg]
    enums: seq[Enum]
  Proto = object
    name, xmlPath: string
    ifaces: seq[Iface]

const
  # Types already declared by hand in wl/core.nim.
  coreIfaces = ["wl_display"].toHashSet
  nimKeywords = [
    "addr", "and", "as", "asm", "bind", "block", "break", "case", "cast",
    "concept", "const", "continue", "converter", "defer", "discard", "distinct",
    "div", "do", "elif", "else", "end", "enum", "except", "export", "finally",
    "for", "from", "func", "if", "import", "in", "include", "interface", "is",
    "isnot", "iterator", "let", "macro", "method", "mixin", "mod", "nil", "not",
    "notin", "object", "of", "or", "out", "proc", "ptr", "raise", "ref",
    "return", "shl", "shr", "static", "template", "try", "tuple", "type",
    "using", "var", "when", "while", "xor", "yield"].toHashSet

proc camel(name: string): string =
  for part in name.split('_'):
    result.add part.capitalizeAscii

proc ident(name: string): string =
  ## Escapes Nim keywords with backticks.
  let n = name.strip(leading = false, chars = {'_'}) # Nim idents can't end in '_'
  if n in nimKeywords: "`" & n & "`" else: n

proc elems(n: XmlNode, tag: string): seq[XmlNode] =
  for c in n.items:
    if c.kind == xnElement and c.tag == tag:
      result.add c

proc parseMsg(n: XmlNode): Msg =
  result.name = n.attr("name")
  result.since = if n.attr("since").len > 0: parseInt(n.attr("since")) else: 1
  result.destructor = n.attr("type") == "destructor"
  for d in n.elems("description"):
    result.summary = d.attr("summary")
  for a in n.elems("arg"):
    result.args.add Arg(name: a.attr("name"), kind: a.attr("type"), iface: a.attr("interface"))

proc parseProto(path: string): Proto =
  let root = loadXml(path)
  result.xmlPath = path
  result.name = root.attr("name")
  for i in root.elems("interface"):
    var iface = Iface(name: i.attr("name"), version: parseInt(i.attr("version")))
    for r in i.elems("request"): iface.requests.add parseMsg(r)
    for e in i.elems("event"): iface.events.add parseMsg(e)
    for en in i.elems("enum"):
      var e = Enum(name: en.attr("name"))
      for entry in en.elems("entry"):
        e.entries.add Entry(name: entry.attr("name"), value: entry.attr("value"))
      iface.enums.add e
    result.ifaces.add iface

proc typeName(iface: string, known: Table[string, string]): string =
  ## Nim type for an object reference; `pointer` when the interface is unknown.
  if iface.len > 0 and (iface in known or iface in coreIfaces): camel(iface) else: "pointer"

proc eventType(a: Arg, known: Table[string, string]): string =
  case a.kind
  of "int": "int32"
  of "uint": "uint32"
  of "fixed": "WlFixed"
  of "string": "cstring"
  of "object", "new_id": typeName(a.iface, known)
  of "array": "ptr WlArray"
  of "fd": "cint"
  else: quit "unknown arg type " & a.kind

proc paramNames(m: Msg): seq[string] =
  ## Argument names, made unique against the implicit `data`/`self` params.
  for a in m.args:
    result.add (if a.name in ["data", "self"]: "arg_" & a.name else: a.name)

proc hexLiteral(v: string): string =
  # "0x1" / "1" / "-1" -> uint32 literal where possible.
  if v.startsWith("-"): "(" & v & ").uint32" else: v & "'u32"

proc generate(p: Proto, known: Table[string, string]): string =
  var deps = initOrderedSet[string]()
  for i in p.ifaces:
    for m in i.requests & i.events:
      for a in m.args:
        if a.iface.len > 0 and a.iface in known and known[a.iface] != p.name:
          deps.incl known[a.iface]

  var o: seq[string]
  o.add "# Generated by tools/wlgen.nim from protocol/" & p.xmlPath.extractFilename & " - DO NOT EDIT."
  o.add "# Regenerate with `nimble wlgen`."
  o.add ""
  o.add "import ../core"
  for d in deps: o.add "import ./" & d
  if p.name != "wayland":
    o.add "{.compile: \"" & p.name & "_protocol.c\".}"
  o.add "export core"
  o.add ""

  # Opaque proxy types
  o.add "type"
  for i in p.ifaces:
    if i.name in coreIfaces: continue
    o.add "  " & camel(i.name) & "Obj* = object"
    o.add "  " & camel(i.name) & "* = ptr " & camel(i.name) & "Obj"
  o.add ""

  # Listener types
  var haveListener: seq[Iface]
  for i in p.ifaces:
    if i.events.len > 0: haveListener.add i
  if haveListener.len > 0:
    o.add "type"
    for i in haveListener:
      o.add "  " & camel(i.name) & "Listener* = object"
      for e in i.events:
        var ps = @["data: pointer", "self: " & camel(i.name)]
        let names = paramNames(e)
        for k, a in e.args:
          ps.add ident(names[k]) & ": " & eventType(a, known)
        o.add "    " & ident(e.name) & "*: proc (" & ps.join("; ") & ") {.cdecl.}"
    o.add ""

  # Interface tables (defined in the scanner C file / libwayland) and versions;
  # declared up front since requests reference each other's tables.
  for i in p.ifaces:
    o.add "var " & i.name & "_interface* {.importc: \"" & i.name & "_interface\".}: WlInterface"
    o.add "const " & i.name.toUpperAscii & "_VERSION* = " & $i.version & "'u32"
  o.add ""

  for i in p.ifaces:
    let T = camel(i.name)
    o.add "# --- " & i.name & " ---"
    o.add ""

    for en in i.enums:
      for e in en.entries:
        o.add "const " & (i.name & "_" & en.name & "_" & e.name).toUpperAscii &
          "* = " & hexLiteral(e.value)
      o.add ""

    o.add "proc " & i.name & "_get_user_data*(self: " & T & "): pointer {.inline.} ="
    o.add "  wl_proxy_get_user_data(cast[ptr WlProxy](self))"
    o.add "proc " & i.name & "_set_user_data*(self: " & T & ", data: pointer) {.inline.} ="
    o.add "  wl_proxy_set_user_data(cast[ptr WlProxy](self), data)"
    o.add "proc " & i.name & "_get_version*(self: " & T & "): uint32 {.inline.} ="
    o.add "  wl_proxy_get_version(cast[ptr WlProxy](self))"
    o.add ""

    if i.events.len > 0:
      o.add "proc " & i.name & "_add_listener*(self: " & T & ", listener: ptr " & T &
        "Listener, data: pointer): cint {.inline.} ="
      o.add "  wl_proxy_add_listener(cast[ptr WlProxy](self), cast[ptr pointer](listener), data)"
      o.add ""
      # no-op handlers so partial listeners are safe (libwayland would call NULL)
      for e in i.events:
        var ps = @["data: pointer", "self: " & T]
        let names = paramNames(e)
        for k, a in e.args: ps.add ident(names[k]) & ": " & eventType(a, known)
        o.add "proc noop_" & i.name & "_" & e.name & "(" & ps.join("; ") & ") {.cdecl.} = discard"
      o.add "proc " & i.name & "_noop_listener*(): " & T & "Listener ="
      o.add "  " & T & "Listener("
      for k, e in i.events:
        o.add "    " & ident(e.name) & ": noop_" & i.name & "_" & e.name &
          (if k < i.events.high: "," else: "")
      o.add "  )"
      o.add ""

    for opcode, r in i.requests:
      var params = @["self: " & T]
      var varargs: seq[string]
      var ret = ""
      var ifaceExpr = "nil"
      var versionExpr = "wl_proxy_get_version(cast[ptr WlProxy](self))"
      let names = paramNames(r)
      for k, a in r.args:
        let n = ident(names[k])
        case a.kind
        of "int":
          params.add n & ": int32"; varargs.add n
        of "uint":
          params.add n & ": uint32"; varargs.add n
        of "fixed":
          params.add n & ": WlFixed"; varargs.add n
        of "string":
          params.add n & ": cstring"; varargs.add n
        of "array":
          params.add n & ": ptr WlArray"; varargs.add "cast[pointer](" & n & ")"
        of "fd":
          params.add n & ": cint"; varargs.add n
        of "object":
          params.add n & ": " & typeName(a.iface, known)
          varargs.add "cast[pointer](" & n & ")"
        of "new_id":
          if a.iface.len > 0:
            ret = camel(a.iface)
            ifaceExpr = "addr " & a.iface & "_interface"
            varargs.add "cast[pointer](nil)"
          else:
            # untyped new_id (wl_registry.bind): interface name + version
            # are marshalled explicitly, the caller gets a raw pointer back.
            params.add "iface: ptr WlInterface"
            params.add "version: uint32"
            ret = "pointer"
            ifaceExpr = "iface"
            versionExpr = "version"
            varargs.add "iface.name"
            varargs.add "version"
            varargs.add "cast[pointer](nil)"
        else: quit "unknown arg type " & a.kind
      let flags = if r.destructor: "1'u32" else: "0'u32"
      var call = "wl_proxy_marshal_flags(cast[ptr WlProxy](self), " & $opcode & "'u32, " &
        ifaceExpr & ", " & versionExpr & ", " & flags
      for v in varargs: call.add ", " & v
      call.add ")"
      let sig = "proc " & i.name & "_" & r.name & "*(" & params.join(", ") & ")" &
        (if ret.len > 0: ": " & ret else: "") & " {.inline.} ="
      o.add sig
      if r.summary.len > 0:
        o.add "  ## " & r.summary.replace("\n", " ") &
          (if r.since > 1: " (since version " & $r.since & ")" else: "")
      if ret.len > 0:
        o.add "  cast[" & ret & "](" & call & ")"
      else:
        o.add "  discard " & call
      o.add ""
  result = o.join("\n")

proc main() =
  let root = currentSourcePath().parentDir.parentDir
  let protoDir = if paramCount() >= 1: paramStr(1) else: root / "protocol"
  let outDir = if paramCount() >= 2: paramStr(2) else: root / "src" / "nimdowpkg" / "wl" / "protocols"
  createDir outDir

  var files: seq[string]
  for f in walkFiles(protoDir / "*.xml"): files.add f
  files.sort()

  var protos: seq[Proto]
  var known = initTable[string, string]()
  for f in files:
    let p = parseProto(f)
    protos.add p
    for i in p.ifaces: known[i.name] = p.name

  for p in protos:
    writeFile(outDir / p.name & ".nim", generate(p, known))
    if p.name != "wayland":
      let cfile = outDir / p.name & "_protocol.c"
      let (output, code) = execCmdEx("wayland-scanner private-code " & quoteShell(p.xmlPath) &
        " " & quoteShell(cfile))
      if code != 0: quit "wayland-scanner failed for " & p.xmlPath & ":\n" & output
    echo "generated ", p.name

main()
